// Build step (run by wrangler before every dev, deploy and Workers Build: [build] in wrangler.toml).
// Writes build/release.js (the newest database migration this code needs, and when it was built) and checks the
// schedules in wrangler.toml. The office and crew pages are plain files in public/ and need no build.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
mkdirSync('build', { recursive: true });

// the schedules: Cloudflare refuses a day-of-week of 0 (its days are 1-7 from Sunday, or SUN-SAT), and refuses it only
// at the very end of a deploy, after the code is already live, so a bad one fails every build without stopping anything
{
  const toml = readFileSync('wrangler.toml', 'utf8');
  const crons = (/^\s*crons\s*=\s*\[([^\]]*)\]/m.exec(toml) || [])[1] || '';
  for (const c of crons.match(/"[^"]*"/g) || []) {
    const f = c.slice(1, -1).trim().split(/\s+/);
    if (f.length !== 5 || /(^|[,\-/])0($|[,\-/])/.test(f[4])) {
      console.error(
        `build: STOPPED. Schedule ${c} in wrangler.toml: Cloudflare numbers the days 1-7 from Sunday (or SUN-SAT); 0 is refused`
      );
      process.exit(1);
    }
  }
}

// the newest database migration this code needs: the Worker refuses to serve (a "being updated" page, and an alert
// email) until it has been applied, rather than failing half-way through someone's sign-in
import { readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const migs = readdirSync('migrations')
  .filter(f => /^\d{4}_.*\.sql$/.test(f))
  .sort();
writeFileSync(
  'build/release.js',
  `// generated by scripts/build.mjs\nexport const NEEDS_MIGRATION = ${JSON.stringify(migs[migs.length - 1])};\nexport const BUILT_AT = ${JSON.stringify(new Date().toISOString())};\n`
);
// on Cloudflare's own build (Workers Builds): stop the deploy if a migration has not been applied to the live database
if (process.env.WORKERS_CI) {
  let listed = null;
  try {
    listed = execFileSync('npx', ['wrangler', 'd1', 'migrations', 'list', 'tmwerx', '--remote'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 120000,
    });
  } catch (e) {
    console.warn(
      'build: could not check the live database migrations (' +
        String(e.message).split('\n')[0] +
        '); the Worker checks again when it starts'
    );
  }
  if (listed != null) {
    const pending = migs.filter(f => listed.includes(f));
    if (pending.length && !/No migrations to apply/i.test(listed)) {
      console.error(
        'build: STOPPED. Apply these database migrations to the live database first: ' +
          pending.join(', ') +
          '\n  npx wrangler d1 migrations apply tmwerx --remote'
      );
      process.exit(1);
    }
    console.log('build: live database migrations up to date');
  }
}
